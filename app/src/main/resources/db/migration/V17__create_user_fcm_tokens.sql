-- FCM 디바이스 토큰 (유저당 다중 기기 허용, token 은 전역 unique)

CREATE TABLE user_fcm_tokens (
    fcm_token_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL,
    token         VARCHAR(512)  NOT NULL,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_fcm_tokens_user
        FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT uk_user_fcm_tokens_token
        UNIQUE (token)
);

CREATE INDEX idx_user_fcm_tokens_user
    ON user_fcm_tokens(user_id);
