-- 백오피스 관리자 계정. 스키마 소유는 앱 서버 Flyway이고, 읽고 쓰는 쪽은 admin-backend다.

CREATE TABLE admin_accounts (
    admin_account_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id          VARCHAR(50)  NOT NULL,
    password_hash     VARCHAR(100) NOT NULL,
    display_name      VARCHAR(30)  NOT NULL,
    role              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at        TIMESTAMP,
    CONSTRAINT uq_admin_accounts_login_id UNIQUE (login_id),
    CONSTRAINT ck_admin_accounts_role
        CHECK (role IN ('ADMIN', 'OWNER')),
    CONSTRAINT ck_admin_accounts_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
